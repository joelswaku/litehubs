export const messages: Record<Locale, Record<TranslationKey, string>> = {
  fr,
  en,
};

export function translate(
  locale: Locale,
  key: TranslationKey,
  values?: Values,
): string {
  const template = messages[locale][key] ?? messages[DEFAULT_LOCALE][key];
  if (!values) return template;
  return template.replace(/{{(\w+)}}/g, (_, name: string) =>
    String(values[name] ?? ""),
  );
}

export function navTranslationKey(label: string): TranslationKey {
  const special: Record<string, TranslationKey> = {
    "Sales & money": "nav.sales_money",
    "Sites & provinces": "nav.sites_provinces",
  };
  if (special[label]) return special[label];
  return `nav.${label
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_|_$/g, "")}` as TranslationKey;
}
